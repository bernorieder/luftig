// MARK: - Strikethrough (GFM) and footnotes

private func specStrikeFootnote() {
    specGroupStart("strikethrough")
    let S = SpecKind.spec
    sx(S, "~~Hi~~ Hello", "[strike·marker:~~][strike:Hi][strike·marker:~~][: Hello]")
    sh(S, "~~**bold strike**~~ and **~~x~~** and ~~*zz*~~", ["+strike,bold bold strike", "+bold,strike x", "+strike,italic zz"])
    sh(S, "~~a\nb~~", ["+strike a", "+strike b"])
    spPlain(S, "This ~~has a\n\nnew paragraph~~.")
    spPlain(S, "~~ a ~~")
    spPlain(S, "~~x")
    spPlain(S, "a ~~~x~~~")
    sh(S, "a~~b~~c", ["+strike b", "plain a", "plain c"])
    let J = SpecKind.judge
    // GFM also accepts one tilde on each side; this editor deliberately does not because ~ is common in prose
    sh(J, "~Hi~ and ~there~", ["+strike Hi"], accept: ["plain ~Hi~ and ~there~"], "single-tilde strikethrough")
    spPlain(J, "~/.config and ~5 MB and about ~10 or ~/bin")
    spPlain(J, "a ~ b ~ c")
    sh(J, "cost ~~$5~~ now ~~$4~~", ["+strike $5", "+strike $4"])

    specGroupStart("footnote")
    sx(S, "A[^1] and B[^long-name].\n\n[^1]: one\n[^long-name]: two\n", "[:A][marker·fn:[^][fn:1][marker·fn:]][: and B][marker·fn:[^][fn:long-name][marker·fn:]][:.⏎⏎][marker·fn:[^][fn:1][marker·fn:]:][: one⏎][marker·fn:[^][fn:long-name][marker·fn:]:][: two⏎]")
    sh(S, "[^1]: Text with *em* and `code`.\n    Second line, indented.\n", ["+italic em", "+code code"])
}
