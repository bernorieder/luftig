// MARK: - Autolinks and bare URLs (6.4 and GFM extended autolinks)

private func specAutolinks() {
    specGroupStart("autolink")
    let S = SpecKind.spec
    func ac(_ s: String) -> String { "[marker·auto:<][auto:\(s)][marker·auto:>]" }
    for u in ["http://foo.bar.baz", "http://foo.bar.baz/test?q=hello&id=22&boolean", "irc://foo.bar:2233/baz", "MAILTO:FOO@BAR.BAZ",
              "a+b+c:d", "made-up-scheme://foo,bar", "http://../", "localhost:5001/foo", "http://example.com/\\[\\", "https://example.com/a_b_c*d*"] {
        sx(S, "<\(u)>", ac(u))
    }
    for u in ["foo@bar.example.com", "foo+special@Bar.baz-bar0.com", "a@b.co"] { sx(S, "<\(u)>", ac(u)) }
    sx(S, "<http://foo.bar/baz bim>", "[:<][auto:http://foo.bar/baz][: bim>]", "not an autolink (core CommonMark); GFM links the bare URL inside it, as the cmark-gfm oracle does")
    // The backslash is an ordinary escape (the text renders as <foo+@bar.example.com>); the angle brackets are not an autolink.
    sx(S, "<foo\\+@bar.example.com>", "[:<foo][esc:\\+][:@bar.example.com>]", "a backslash is not allowed in an e-mail autolink")
    spPlain(S, "<>")
    sx(S, "< http://foo.bar >", "[:< ][auto:http://foo.bar][: >]", "GFM: the bare URL inside is an extended autolink")
    spPlain(S, "<m:abc>")
    spPlain(S, "<foo.bar.baz>")
    sh(S, "<https://x.org/a_b_c> and <https://y.org/*z*>", ["+auto https://x.org/a_b_c", "-italic a_b_c", "+auto https://y.org/*z*", "-italic *z*"])
    // GFM extended autolinks
    sh(S, "http://example.com", ["+auto http://example.com"])
    sh(S, "https://example.com/path?x=1&y=2#frag", ["+auto https://example.com/path?x=1&y=2#frag"])
    sh(S, "www.commonmark.org", ["+auto www.commonmark.org"])
    sh(S, "Visit www.commonmark.org/help for more information.", ["plain Visit ", "+auto www.commonmark.org/help", "plain  for more information."])
    sx(S, "Visit www.commonmark.org.\n\nVisit www.commonmark.org/a.b.", "[:Visit ][auto:www.commonmark.org][:.⏎⏎Visit ][auto:www.commonmark.org/a.b][:.]")
    sh(S, "www.google.com/search?q=Markup+(business)", ["+auto www.google.com/search?q=Markup+(business)"])
    sx(S, "www.google.com/search?q=Markup+(business)))", "[auto:www.google.com/search?q=Markup+(business)][:))]")
    sx(S, "(www.google.com/search?q=Markup+(business))", "[:(][auto:www.google.com/search?q=Markup+(business)][:)]")
    sx(S, "(www.google.com/search?q=Markup+(business)", "[:(][auto:www.google.com/search?q=Markup+(business)]")
    sh(S, "www.google.com/search?q=(business))+ok", ["+auto www.google.com/search?q=(business))+ok"], accept: ["+auto www.google.com/search?q=(business)", "plain )+ok"], "an unbalanced ) ends a bare URL even when more URL characters follow (GFM would continue; documented)")
    sh(S, "www.commonmark.org/he<lp", ["+auto www.commonmark.org/he", "plain <lp"])
    sx(S, "(Visit https://encrypted.google.com/search?q=Markup+(business))", "[:(Visit ][auto:https://encrypted.google.com/search?q=Markup+(business)][:)]")
    sh(S, "http://commonmark.org\n\n(Visit https://x.org)", ["+auto http://commonmark.org", "+auto https://x.org", "plain )"])
    sh(S, "www.google.com/search?q=commonmark&hl;", ["+auto www.google.com/search?q=commonmark", "-auto &hl;"], "GFM example: a trailing entity-like &hl; is not part of the link")
    sh(S, "www.google.com/search?q=commonmark&hl=en", ["+auto www.google.com/search?q=commonmark&hl=en"])
    sh(S, "[a www.x.org](/u) and w[ www.x.org", ["-auto www.x.org", "-auto www.x.org@@2"], "no autolink while a bracket opener is open (cmark-gfm)")
    sh(S, "www.foo_bar.com and http://my_host/path", ["plain www.foo_bar.com", "plain http://my_host/path"], accept: ["+auto www.foo_bar.com", "+auto http://my_host/path"], "GFM: no underscores in the last two labels of the domain (the lexer does not validate the domain)")
    sh(S, "Anonymous FTP is available at ftp://foo.bar.baz.", ["+auto ftp://foo.bar.baz"], accept: ["plain ftp://foo.bar.baz."], "ftp:// bare URLs")
    sh(S, "mail foo@bar.baz now", ["+auto foo@bar.baz"], accept: ["plain foo@bar.baz"], "bare e-mail autolink (GFM)")
    specGroupStart("autolink-prose")
    let J = SpecKind.judge
    sh(J, "Go to https://en.wikipedia.org/wiki/Snake_case_(naming) now.", ["+auto https://en.wikipedia.org/wiki/Snake_case_(naming)", "plain  now."])
    sh(J, "See https://example.com/a_b_c/d_e_f_.", ["+auto https://example.com/a_b_c/d_e_f", "plain _.", ], "trailing underscore and period are excluded")
    sh(J, "Docs: https://docs.example.com/api/v1/users?id=_x_&q=*y*.", ["+auto https://docs.example.com/api/v1/users?id=_x_&q=*y", "-italic _x_"])
    sh(J, "https://example.com/~user/file_name.tar.gz, and http://localhost:8080/x_y!", ["+auto https://example.com/~user/file_name.tar.gz", "+auto http://localhost:8080/x_y", "plain !"])
    sh(J, "<https://example.com>, (https://example.com), \"https://example.com\", 'https://example.com'", ["+auto https://example.com", "+auto https://example.com@@2", "+auto https://example.com@@3", "+auto https://example.com@@4"])
    sh(J, "*https://example.com/a*", ["+italic,auto https://example.com/a", "+italic,marker *"])
    sh(J, "**https://example.com/a_b**", ["+bold,auto https://example.com/a_b"])
    sh(J, "[https://example.com](https://example.com/x_y)", ["+link https://example.com", "-auto https://example.com", "+dest https://example.com/x_y"])
    sh(J, "http://127.0.0.1:3000/a and http://[::1]:8080/b and https://user:pw@host.example/c", ["+auto http://127.0.0.1:3000/a", "+auto https://user:pw@host.example/c"])
    spPlain(J, "ahttps://x.org and xhttp://y")
    spPlain(J, "https:// and http: and www and www. alone")
    sx(J, "See www.example.com/a_b_c_d and also www.x.org.", "[:See ][auto:www.example.com/a_b_c_d][: and also ][auto:www.x.org][:.]")
    spPlain(J, "e.g. file.md and README.md and v1.2.3 and example.com")
    sh(J, "Contact: <me@example.com>.", ["+auto me@example.com"])
    sh(J, "URL in quotes: \"http://x.org/a?b=c\".", ["+auto http://x.org/a?b=c", "plain \"."])
    sh(J, "http://x.org/a-b_c.d/e%20f/ü", ["+auto http://x.org/a-b_c.d/e%20f/ü"])
    // Review round: http(s):// after any non-letter (cmark-gfm only looks back over letters), never inside link text; www. stays strict.
    sh(J, "url=http://k.org/v and ,http://d.org and :http://e.org and a<b>http://h.org</b>", ["+auto http://k.org/v", "+auto http://d.org", "+auto http://e.org", "+auto http://h.org"], "any non-letter may precede http(s)://")
    sh(J, "[http://t.org](http://u.org)", ["+link http://t.org", "-auto http://t.org", "+dest http://u.org"], "no autolink inside link text")
    sh(J, "[http://b.org/y] stays as typed", ["plain [http://b.org/y]"], "a bracketed bare URL (cmark-gfm does not link it either)")
    sh(J, "\"www.q.org\" and \"x\"www.z.org", ["plain \"www.q.org\"", "plain www.z.org"], "www. still needs start / blank / * _ ~ (")
}

