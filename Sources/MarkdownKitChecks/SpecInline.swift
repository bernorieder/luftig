import Foundation
import MarkdownKit

// Independent conformance suite, inline constructs. See SpecHarness.swift for the notation and the verdicts.

func runSpecInline() {
    specEmphasis()
    specCodeSpans()
    specLinks()
    specImages()
    specAutolinks()
    specEscapesEntitiesHTML()
    specStrikeFootnote()
}

// MARK: - Emphasis and strong emphasis (CommonMark 0.31 section 6.2, plus intraword idioms)

private func specEmphasis() {
    specGroupStart("emphasis")
    let S = SpecKind.spec
    // Rules 1-2, 5-6 (single delimiters)
    sx(S, "*foo bar*", "[italic·marker:*][italic:foo bar][italic·marker:*]")
    spPlain(S, "a * foo bar*")
    spPlain(S, "a*\"foo\"*")
    sx(S, "* a *", "[list:* ][:a *]")
    sx(S, "foo*bar*", "[:foo][italic·marker:*][italic:bar][italic·marker:*]")
    sx(S, "5*6*78", "[:5][italic·marker:*][italic:6][italic·marker:*][:78]")
    sx(S, "_foo bar_", "[italic·marker:_][italic:foo bar][italic·marker:_]")
    spPlain(S, "_ foo bar_")
    spPlain(S, "a_\"foo\"_")
    spPlain(S, "foo_bar_")
    spPlain(S, "5_6_78")
    spPlain(S, "пристаням_стремятся_")
    spPlain(S, "aa_\"bb\"_cc")
    sx(S, "foo-_(bar)_", "[:foo-][italic·marker:_][italic:(bar)][italic·marker:_]")
    spPlain(S, "_foo*")
    spPlain(S, "*foo bar *")
    spPlain(S, "*foo bar\n*")
    spPlain(S, "*(*foo)")
    sh(S, "*(*foo*)*", ["+italic (", "+italic foo", "+italic )"])
    sx(S, "*foo*bar", "[italic·marker:*][italic:foo][italic·marker:*][:bar]")
    spPlain(S, "_foo bar _")
    spPlain(S, "_(_foo)")
    sh(S, "_(_foo_)_", ["+italic (", "+italic foo", "+italic )"])
    spPlain(S, "_foo_bar")
    spPlain(S, "_пристаням_стремятся")
    sx(S, "_foo_bar_baz_", "[italic·marker:_][italic:foo_bar_baz][italic·marker:_]")
    sx(S, "_(bar)_.", "[italic·marker:_][italic:(bar)][italic·marker:_][:.]")
    // Strong
    sx(S, "**foo bar**", "[bold·marker:**][bold:foo bar][bold·marker:**]")
    spPlain(S, "** foo bar**")
    spPlain(S, "a**\"foo\"**")
    sx(S, "foo**bar**", "[:foo][bold·marker:**][bold:bar][bold·marker:**]")
    sx(S, "__foo bar__", "[bold·marker:__][bold:foo bar][bold·marker:__]")
    spPlain(S, "__ foo bar__")
    spPlain(S, "__\nfoo bar__")
    spPlain(S, "a__\"foo\"__")
    spPlain(S, "foo__bar__")
    spPlain(S, "5__6__78")
    spPlain(S, "пристаням__стремятся__")
    sh(S, "__foo, __bar__, baz__", ["+bold foo, ", "+bold bar", "+bold , baz"])
    sx(S, "foo-__(bar)__", "[:foo-][bold·marker:__][bold:(bar)][bold·marker:__]")
    spPlain(S, "**foo bar **")
    spPlain(S, "**(**foo)")
    sh(S, "*(**foo**)*", ["+italic (", "+italic,bold foo", "+italic )"])
    sh(S, "**Gomphocarpus (*Gomphocarpus physocarpus*, syn.\n*Asclepias physocarpa*)**",
       ["+bold Gomphocarpus (", "+bold,italic Gomphocarpus physocarpus", "+bold,italic Asclepias physocarpa", "-italic , syn."])
    sh(S, "**foo \"*bar*\" foo**", ["+bold foo \"", "+bold,italic bar", "-italic foo \""])
    sx(S, "**foo**bar", "[bold·marker:**][bold:foo][bold·marker:**][:bar]")
    spPlain(S, "__foo bar __")
    spPlain(S, "__(__foo)")
    sh(S, "_(__foo__)_", ["+italic (", "+italic,bold foo", "+italic )"])
    spPlain(S, "__foo__bar")
    spPlain(S, "__пристаням__стремятся")
    sx(S, "__foo__bar__baz__", "[bold·marker:__][bold:foo__bar__baz][bold·marker:__]")
    sx(S, "__(bar)__.", "[bold·marker:__][bold:(bar)][bold·marker:__][:.]")
    // Nesting and interplay (examples 400-480)
    sh(S, "*foo [bar](/url)*", ["+italic foo ", "+italic,link bar"])
    sx(S, "*foo\nbar*", "[italic·marker:*][italic:foo⏎bar][italic·marker:*]")
    sh(S, "_foo __bar__ baz_", ["+italic foo ", "+italic,bold bar", "+italic  baz"])
    sh(S, "_foo _bar_ baz_", ["+italic foo ", "+italic bar", "+italic  baz"])
    sh(S, "__foo_ bar_", ["+italic foo", "+italic  bar"])
    sh(S, "*foo *bar**", ["+italic foo ", "+italic bar"])
    sh(S, "*foo **bar** baz*", ["+italic foo ", "+italic,bold bar", "+italic  baz"])
    sx(S, "*foo**bar**baz*", "[italic·marker:*][italic:foo][bold·italic·marker:**][bold·italic:bar][bold·italic·marker:**][italic:baz][italic·marker:*]")
    sh(S, "*foo**bar*", ["+italic foo**bar", "-bold foo**bar"])
    sh(S, "***foo** bar*", ["+italic,bold foo", "+italic  bar", "-bold  bar"])
    sh(S, "*foo **bar***", ["+italic foo ", "+italic,bold bar"])
    sh(S, "*foo**bar***", ["+italic foo", "+italic,bold bar"])
    sh(S, "foo***bar***baz", ["plain foo", "+italic,bold bar", "plain baz"])
    sh(S, "foo******bar*********baz", ["plain foo", "+bold bar", "plain ***baz"])
    sh(S, "*foo **bar *baz* bim** bop*", ["+italic foo ", "+bold bar ", "+italic,bold baz", "+bold  bim", "+italic  bop", "-bold  bop"])
    sh(S, "*foo [*bar*](/url)*", ["+italic foo ", "+italic,link bar"])
    spPlain(S, "** is not an empty emphasis")
    spPlain(S, "**** is not an empty strong emphasis")
    sh(S, "**foo [bar](/url)**", ["+bold foo ", "+bold,link bar"])
    sx(S, "**foo\nbar**", "[bold·marker:**][bold:foo⏎bar][bold·marker:**]")
    sh(S, "__foo _bar_ baz__", ["+bold foo ", "+bold,italic bar", "+bold  baz"])
    sh(S, "__foo __bar__ baz__", ["+bold foo ", "+bold bar", "+bold  baz"])
    sh(S, "____foo__ bar__", ["+bold foo", "+bold  bar"])
    sh(S, "**foo **bar****", ["+bold foo ", "+bold bar"])
    sh(S, "**foo *bar* baz**", ["+bold foo ", "+bold,italic bar", "+bold  baz", "-italic  baz"])
    sh(S, "**foo*bar*baz**", ["+bold foo", "+bold,italic bar", "+bold baz"])
    sh(S, "***foo* bar**", ["+bold,italic foo", "+bold  bar", "-italic  bar"])
    sh(S, "**foo *bar***", ["+bold foo ", "+bold,italic bar"])
    sh(S, "**foo *bar **baz**\nbim* bop**", ["+bold foo ", "+italic bar ", "+italic,bold baz", "+italic bim", "+bold bop", "-italic bop"])
    sh(S, "**foo [*bar*](/url)**", ["+bold foo ", "+bold,italic,link bar"])
    spPlain(S, "__ is not an empty emphasis")
    spPlain(S, "____ is not an empty strong emphasis")
    spPlain(S, "foo ***")
    sh(S, "foo *\\**", ["plain foo ", "+italic,esc \\*"])
    sh(S, "foo *_*", ["plain foo ", "+italic _"])
    spPlain(S, "foo *****")
    sh(S, "foo **\\***", ["plain foo ", "+bold,esc \\*"])
    sh(S, "foo **_**", ["plain foo ", "+bold _"])
    sx(S, "**foo*", "[:*][italic·marker:*][italic:foo][italic·marker:*]")
    sx(S, "*foo**", "[italic·marker:*][italic:foo][italic·marker:*][:*]")
    sh(S, "***foo**", ["plain *", "+bold foo"])
    sh(S, "****foo*", ["plain ***", "+italic foo"])
    sx(S, "**foo***", "[bold·marker:**][bold:foo][bold·marker:**][:*]")
    sx(S, "*foo****", "[italic·marker:*][italic:foo][italic·marker:*][:***]")
    spPlain(S, "foo ___")
    sh(S, "foo _\\__", ["plain foo ", "+italic,esc \\_"])
    sh(S, "foo _*_", ["plain foo ", "+italic *"])
    spPlain(S, "foo _____")
    sh(S, "foo __\\___", ["plain foo ", "+bold,esc \\_"])
    sh(S, "foo __*__", ["plain foo ", "+bold *"])
    sx(S, "__foo_", "[:_][italic·marker:_][italic:foo][italic·marker:_]")
    sx(S, "_foo__", "[italic·marker:_][italic:foo][italic·marker:_][:_]")
    sh(S, "___foo__", ["plain _", "+bold foo"])
    sh(S, "____foo_", ["plain ___", "+italic foo"])
    sx(S, "__foo___", "[bold·marker:__][bold:foo][bold·marker:__][:_]")
    sx(S, "_foo____", "[italic·marker:_][italic:foo][italic·marker:_][:___]")
    // Code spans, links and raw HTML bind tighter than emphasis
    sh(S, "*foo`*`", ["plain *foo", "+code *@@2"])
    sh(S, "*a `*`*", ["+italic a ", "+italic,code *@@2"])
    sh(S, "_a `_`_", ["+italic a ", "+italic,code _@@2"])
    sh(S, "*[foo*](/uri)", ["plain *", "+link foo*", "-italic foo*"])
    sh(S, "_foo [bar_](/url)", ["plain _foo ", "+link bar_", "-italic bar_"])
    sh(S, "[foo *bar](baz*)", ["+link foo *bar", "+dest baz*", "-italic foo *bar"])
    sh(S, "*foo [bar* baz]", ["+italic foo [bar", "plain  baz]"])
    sh(S, "*<img src=\"foo\" title=\"*\"/>", ["plain *", "+html <img src=\"foo\" title=\"*\"/>", "-italic <img"])
    sh(S, "**<a href=\"**\">", ["plain **", "+html <a href=\"**\">"])
    sh(S, "__<a href=\"__\">", ["plain __", "+html <a href=\"__\">"])
    sh(S, "**a<https://foo.bar/?q=**>", ["plain **a", "+auto https://foo.bar/?q=**", "-bold https://foo.bar/?q=**"])
    sh(S, "__a<https://foo.bar/?q=__>", ["plain __a", "+auto https://foo.bar/?q=__"])
    // Emphasis never crosses a paragraph boundary
    spPlain(S, "*foo\n\nbar*")
    spPlain(S, "**foo\n\nbar**")

    specGroupStart("emphasis-prose")
    let J = SpecKind.judge
    // Intraword underscores: identifiers, file names, math - the commonest false positives in ordinary writing.
    spPlain(J, "snake_case_words")
    spPlain(J, "_private_var")
    spPlain(J, "use _private_var and _other_var here")
    spPlain(J, "my_var_name_")
    spPlain(J, "some_module.some_function_name()")
    spPlain(J, "see my_file_name.txt and other_file_name.md for details")
    spPlain(J, "x_i + y_j = z_k")
    spPlain(J, "The variable _x and the variable _y")
    spPlain(J, "path/to/some_dir/another_dir/file_name.py")
    spPlain(J, "MAX_VALUE_ and MIN_VALUE_")
    spPlain(J, "a_b_c_d_e")
    spPlain(J, "__proto__x")
    // Star idioms
    spPlain(J, "2 * 3 * 4 = 24")
    spPlain(J, "a * b")
    spPlain(J, "src/**/*.swift")
    spPlain(J, "match **/*.md files")
    spPlain(J, "git add *.swift *.md")
    spPlain(J, "def f(*args, **kwargs): pass")
    spPlain(J, "pointer * and another *")
    spPlain(J, "5 * (3 + 4)")
    spPlain(J, "wait ** what")
    // CommonMark says these ARE emphasis (and renderers agree), so the editor shows what the reader will see
    sx(SpecKind.spec, "__init__.py", "[bold·marker:__][bold:init][bold·marker:__][:.py]")
    sx(SpecKind.spec, "a*b*c", "[:a][italic·marker:*][italic:b][italic·marker:*][:c]")
    sx(SpecKind.spec, "2*3*4", "[:2][italic·marker:*][italic:3][italic·marker:*][:4]")
    sx(SpecKind.spec, "__pycache__/", "[bold·marker:__][bold:pycache][bold·marker:__][:/]")
    sh(J, "**Note:** be *careful* with _this_ and __that__.", ["+bold Note:", "+italic careful", "+italic this", "+bold that", "plain  be "])
    sh(J, "**Note**: text", ["+bold Note", "plain : text"])
    sh(J, "**bold**, *italic*, and `code`.", ["+bold bold", "plain , ", "+italic italic", "+code code"])
    sh(J, "(*note*) and [**x**]", ["+italic note", "plain (", "+bold x"])
    sh(J, "He said \"**wow**\" and '*hm*'.", ["+bold wow", "+italic hm"])
    sh(J, "**bold**text and text**bold**", ["+bold bold", "+bold bold@@2"])
    sh(J, "*emphasis*, **strong**; _under_: __dunder__!", ["+italic emphasis", "+bold strong", "+italic under", "+bold dunder"])
    // Unicode
    sx(J, "日本*語*です", "[:日本][italic·marker:*][italic:語][italic·marker:*][:です]")
    sh(J, "**日本語**です", ["+bold 日本語"])
    sh(J, "*مرحبا* بالعالم", ["+italic مرحبا", "plain  بالعالم"])
    sh(J, "*😀* and **👍🏽** ok", ["+italic 😀", "+bold 👍🏽"])
    sh(J, "_é_ _ñandú_ *Ünïcode*", ["+italic é", "+italic ñandú", "+italic Ünïcode"])
    spPlain(J, "naïve_café_au_lait")
    spPlain(J, "日本語_テスト_です")
    // CJK punctuation next to a delimiter: CommonMark's flanking rules make this NOT emphasis (known CJK limitation)
    sh(SpecKind.spec, "**「日本語」**です", ["plain **「日本語」**です"])
}

// MARK: - Code spans (6.1)

private func specCodeSpans() {
    specGroupStart("code-span")
    let S = SpecKind.spec
    sx(S, "`foo`", "[code·marker:`][code:foo][code·marker:`]")
    sx(S, "`` foo ` bar ``", "[code·marker:``][code: foo ` bar ][code·marker:``]")
    sx(S, "` `` `", "[code·marker:`][code: `` ][code·marker:`]")
    sx(S, "`  ``  `", "[code·marker:`][code:  ``  ][code·marker:`]")
    sx(S, "` a`", "[code·marker:`][code: a][code·marker:`]")
    sx(S, "` `\n`  `", "[code·marker:`][code: ][code·marker:`][:⏎][code·marker:`][code:  ][code·marker:`]")
    sx(S, "``\nfoo\nbar  \nbaz\n``", "[code·marker:``][code:⏎foo⏎bar  ⏎baz⏎][code·marker:``]")
    sx(S, "``\nfoo \n``", "[code·marker:``][code:⏎foo ⏎][code·marker:``]")
    sx(S, "`foo   bar \nbaz`", "[code·marker:`][code:foo   bar ⏎baz][code·marker:`]")
    sx(S, "`foo\\`bar`", "[code·marker:`][code:foo\\][code·marker:`][:bar`]")
    sx(S, "``foo`bar``", "[code·marker:``][code:foo`bar][code·marker:``]")
    sx(S, "` foo `` bar `", "[code·marker:`][code: foo `` bar ][code·marker:`]")
    sx(S, "*foo`*`", "[:*foo][code·marker:`][code:*][code·marker:`]")
    sx(S, "[not a `link](/foo`)", "[:[not a ][code·marker:`][code:link](/foo][code·marker:`][:)]")
    sx(S, "`<a href=\"`\">`", "[code·marker:`][code:<a href=\"][code·marker:`][:\">`]")
    sx(S, "<a href=\"`\">`", "[html:<a href=\"`\">][:`]")
    sx(S, "`<https://foo.bar.`baz>`", "[code·marker:`][code:<https://foo.bar.][code·marker:`][:baz>`]")
    sx(S, "<https://foo.bar.`baz>`", "[marker·auto:<][auto:https://foo.bar.`baz][marker·auto:>][:`]")
    spPlain(S, "```foo``")
    spPlain(S, "`foo")
    sx(S, "`foo``bar``", "[:`foo][code·marker:``][code:bar][code·marker:``]")
    sx(S, "``` ```\naaa", "[code·marker:```][code: ][code·marker:```][:⏎aaa]")
    sx(S, "`` ` ``", "[code·marker:``][code: ` ][code·marker:``]")
    sh(S, "`a` and `b` and `c`", ["+code a", "plain  and ", "+code b", "+code c"])
    sh(S, "`**not bold**` and `_not it_`", ["+code **not bold**", "-bold **not bold**", "+code _not it_", "-italic _not it_"])
    sh(S, "`[not](a link)` `<b>x</b>` `https://x.org`", ["+code [not](a link)", "-link [not](a link)", "-html <b>x</b>", "-auto https://x.org"])
    sh(S, "`a\\*b`", ["+code a\\*b", "-esc a\\*b"])
    sh(S, "`&amp;`", ["+code &amp;", "-esc &amp;"])
    sh(SpecKind.judge, "Use `git commit -m \"msg\"` then `git push`.", ["+code git commit -m \"msg\"", "plain  then ", "+code git push"])
    sh(SpecKind.judge, "``foo`` `` `bar` ``", ["+code foo", "+code `bar`"])
    spPlain(SpecKind.judge, "a ` b and c")
}

// MARK: - Links, references, footnotes (6.3)

private func specLinks() {
    specGroupStart("link")
    let S = SpecKind.spec
    let L = "[marker·link:[][link:link][marker·link:]]"
    func d(_ inner: String) -> String { "[marker·dest:(]\(inner)[marker·dest:)]" }
    sx(S, "[link](/uri \"title\")", L + d("[dest:/uri][: ][dest:\"title\"]"))
    sx(S, "[link](/uri)", L + d("[dest:/uri]"))
    sx(S, "[link]()", L + "[marker·dest:(][marker·dest:)]")
    sx(S, "[link](<>)", L + d("[dest:<>]"))
    spPlain(S, "[link](/my uri)")
    sx(S, "[link](</my uri>)", L + d("[dest:</my uri>]"))
    spPlain(S, "[link](foo\nbar)")
    spPlain(S, "[link](<foo\nbar>)")
    sx(S, "[a](<b)c>)", "[marker·link:[][link:a][marker·link:]]" + d("[dest:<b)c>]"))
    sh(S, "[link](\\(foo\\))", ["+link link", "+dest \\(foo\\)", "+marker,dest ("])
    sh(S, "[link](foo(and(bar)))", ["+link link", "+dest foo(and(bar))"])
    spPlain(S, "[link](foo(and(bar))")
    sh(S, "[link](foo\\(and\\(bar\\))", ["+link link", "+dest foo\\(and\\(bar\\)"])
    sh(S, "[link](<foo(and(bar)>)", ["+link link", "+dest <foo(and(bar)>"])
    sh(S, "[link](foo\\)\\:)", ["+link link", "+dest foo\\)\\:"])
    sh(S, "[link](#fragment)", ["+dest #fragment"])
    sh(S, "[link](https://example.com#fragment)", ["+dest https://example.com#fragment"])
    sh(S, "[link](https://example.com?foo=3#frag)", ["+dest https://example.com?foo=3#frag"])
    sh(S, "[link](foo\\bar)", ["+dest foo\\bar"])
    sh(S, "[link](foo%20b&auml;)", ["+dest foo%20b&auml;"])
    sh(S, "[link](\"title\")", ["+dest \"title\""])
    sh(S, "[link](/url \"title\")", ["+dest /url", "+dest \"title\""])
    sh(S, "[link](/url 'title')", ["+dest 'title'"])
    sh(S, "[link](/url (title))", ["+dest (title)"])
    sh(S, "[link](/url \"title \\\"&quot;\")", ["+link link", "+dest /url", "+marker,dest )"])
    sh(S, "[link](/url 'title \"and\" title')", ["+link link", "+dest 'title \"and\" title'"])
    spPlain(S, "[link](/url \"title \"and\" title\")")
    sh(S, "[link](   /uri\n  \"title\"  )", ["+link link", "+dest /uri", "+dest \"title\""], accept: ["plain [link](   /uri\n  \"title\"  )"], "link destination and title on different lines (inline syntax is lexed per line; documented)")
    spPlain(S, "[link] (/uri)")
    sh(S, "[link [foo [bar]]](/uri)", ["+link link [foo [bar]]", "+dest /uri"])
    spPlain(S, "[link] bar](/uri)")
    sh(S, "[link [bar](/uri)", ["plain [link ", "+link bar", "+dest /uri"])
    sh(S, "[link \\[bar](/uri)", ["+link link ", "+link \\[bar", "+dest /uri"])
    sh(S, "[link *foo **bar** `#`*](/uri)", ["+link link ", "+link,italic foo ", "+link,bold bar", "+link,code #", "+dest /uri"])
    sh(S, "[![moon](moon.jpg)](/uri)", ["+image ![moon](moon.jpg)", "+dest /uri", "+marker,link ["])
    sh(S, "[foo [bar](/uri)](/uri)", ["plain [foo ", "+link bar", "plain ](/uri)@@2"])
    sh(S, "[foo <bar attr=\"](baz)\">", ["plain [foo ", "+html <bar attr=\"](baz)\">"])
    sh(S, "[foo`](/uri)`", ["plain [foo", "+code ](/uri)"])
    sh(S, "[foo<https://example.com/?search=](uri)>", ["plain [foo", "+auto https://example.com/?search=](uri)"])
    // Link text with an underscore word, dest with underscores / emphasis characters: never emphasis inside a destination
    sh(S, "[snake_case_text](https://x.org/_a_/b*c*)", ["+link snake_case_text", "-italic snake_case_text", "+dest https://x.org/_a_/b*c*", "-italic _a_", "-italic *c*"])
    sh(S, "[a](b)[c](d)", ["+link a", "+link c", "+dest b", "+dest d"])
    sh(S, "see [a](b), [c](d). ok", ["+link a", "+link c", "plain , ", "plain . ok"])
    // Reference links
    sx(S, "[foo][bar]", "[marker·link:[][link:foo][marker·link:]][marker·ref:[][ref:bar][marker·ref:]]")
    sh(S, "[link [foo [bar]]][ref]", ["+link link [foo [bar]]", "+ref ref"])
    sh(S, "[Foo][BaR]", ["+link Foo", "+ref BaR"])
    sx(S, "[foo][]", "[marker·link:[][link:foo][marker·link:]][marker·ref:[]]")
    sh(S, "[*foo* bar][]", ["+link,italic foo", "+link  bar"])
    // Shortcut references need the definition to know: not styled (deliberate), though CommonMark would link them
    sh(S, "[foo]\n\n[foo]: /url \"title\"", ["+link foo"], accept: ["plain [foo]"], "shortcut reference with a definition")
    sh(S, "[foo]: /url", ["+ref foo", "+dest /url"])
    sx(S, "[foo]: /url \"title\"\n", "[marker·ref:[][ref:foo][marker·ref:]:][: ][dest:/url][: ][dest:\"title\"][:⏎]")
    sx(S, "   [foo]: /url\n", "[:   ][marker·ref:[][ref:foo][marker·ref:]:][: ][dest:/url][:⏎]")
    sh(S, "[Foo bar]: <my url> 'title'\n", ["+ref Foo bar", "+dest <my url>", "+dest 'title'"])
    sh(S, "[foo]: /url\n[bar]: /url2\n", ["+ref foo", "+ref bar", "+dest /url2"])
    sh(S, "[foo]:\n/url\n", ["+ref foo", "+dest /url"], accept: ["plain [foo]:"], "definition with the destination on the next line")
    sh(S, "[foo]: /url\n\"title\" ok\n", ["+ref foo"], "line 2 is a paragraph")
    sh(S, "[foo]: /url \"title\" ok\n", ["plain [foo]: /url \"title\" ok"])
    sh(S, "[1]: https://example.com/a_b_c\n", ["+ref 1", "+dest https://example.com/a_b_c", "-italic _b_"])
    // Footnotes (GFM-adjacent, widely used)
    sx(S, "text[^1] more", "[:text][marker·fn:[^][fn:1][marker·fn:]][: more]")
    sx(S, "[^note]: The note.\n", "[marker·fn:[^][fn:note][marker·fn:]:][: The note.⏎]")
    spPlain(S, "[^a b]")
    spPlain(S, "[^]")

    specGroupStart("link-prose")
    let J = SpecKind.judge
    // brackets in ordinary prose are not links
    spPlain(J, "[citation needed] and [1] and [x]")
    spPlain(J, "array[i][j] and a[0]")
    spPlain(J, "[[wiki link]] and [[Page|alias]]")
    spPlain(J, "see [ ] and [x] items")
    spPlain(J, "[TODO]: fix this ( really )")
