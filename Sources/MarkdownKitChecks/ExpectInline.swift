import Foundation
import MarkdownKit

func runInlineExpectations() {
    Harness.group("expectations: inline")
    emphasisTests()
    codeSpanTests()
    linkTests()
    miscInlineTests()
}

private func emphasisTests() {
    ex("*a*", "[italic·marker:*][italic:a][italic·marker:*]")
    ex("_a_", "[italic·marker:_][italic:a][italic·marker:_]")
    ex("**a**", "[bold·marker:**][bold:a][bold·marker:**]")
    ex("__a__", "[bold·marker:__][bold:a][bold·marker:__]")
    ex("***a***", "[italic·marker:*][bold·italic·marker:**][bold·italic:a][bold·italic·marker:**][italic·marker:*]")
    ex("*a **b** c*", "[italic·marker:*][italic:a ][bold·italic·marker:**][bold·italic:b][bold·italic·marker:**][italic: c][italic·marker:*]")
    ex("**a *b* c**", "[bold·marker:**][bold:a ][bold·italic·marker:*][bold·italic:b][bold·italic·marker:*][bold: c][bold·marker:**]")
    ex("*a* *b*", "[italic·marker:*][italic:a][italic·marker:*][: ][italic·marker:*][italic:b][italic·marker:*]")
    ex("snake_case_word", "[:snake_case_word]", "intraword underscores are not emphasis")
    ex("foo_bar_", "[:foo_bar_]")
    ex("_foo_bar", "[:_foo_bar]")
    ex("foo*bar*baz", "[:foo][italic·marker:*][italic:bar][italic·marker:*][:baz]", "intraword stars are emphasis")
    ex("a * b * c", "[:a * b * c]")
    ex("*a", "[:*a]")
    ex("**a", "[:**a]")
    ex("a**", "[:a**]")
    ex("* a*", "[list:* ][:a*]")
    ex("*a **b", "[:*a **b]")
    ex("*foo**bar**baz*", "[italic·marker:*][italic:foo][bold·italic·marker:**][bold·italic:bar][bold·italic·marker:**][italic:baz][italic·marker:*]")
    ex("**foo*", "[:*][italic·marker:*][italic:foo][italic·marker:*]")
    ex("*foo**", "[italic·marker:*][italic:foo][italic·marker:*][:*]")
    ex("**foo bar **", "[:**foo bar **]")
    ex("~~x~~", "[strike·marker:~~][strike:x][strike·marker:~~]")
    ex("a ~~b *c* d~~ e", "[:a ][strike·marker:~~][strike:b ][italic·strike·marker:*][italic·strike:c][italic·strike·marker:*][strike: d][strike·marker:~~][: e]")
    ex("~x~", "[:~x~]")
    ex("a ~~~x~~~", "[:a ~~~x~~~]")
    ex("~~x", "[:~~x]")
    ex("*a\nb*", "[italic·marker:*][italic:a⏎b][italic·marker:*]", "emphasis may span a soft line break inside a paragraph")
    ex("*a\n\nb*", "[:*a⏎⏎b*]", "but never a paragraph boundary")
    ex("> *a\n> b*\n", "[q1·marker:> ][q1·italic·marker:*][q1·italic:a⏎][q1·marker:> ][q1·italic:b][q1·italic·marker:*][q1:⏎]")
    ex("*😀*", "[italic·marker:*][italic:😀][italic·marker:*]")
    ex("日本*語*です", "[:日本][italic·marker:*][italic:語][italic·marker:*][:です]")
    ex("**bold**text", "[bold·marker:**][bold:bold][bold·marker:**][:text]")
    ex("_a_b", "[:_a_b]")
    ex("a _b_", "[:a ][italic·marker:_][italic:b][italic·marker:_]")
    ex("(_a_)", "[:(][italic·marker:_][italic:a][italic·marker:_][:)]")
    ex("*(*foo*)*", "[italic·marker:*][italic:(][italic·marker:*][italic:foo][italic·marker:*][italic:)][italic·marker:*]")
}

private func codeSpanTests() {
    ex("`a`", "[code·marker:`][code:a][code·marker:`]")
    ex("``a`b``", "[code·marker:``][code:a`b][code·marker:``]")
    ex("` a `", "[code·marker:`][code: a ][code·marker:`]")
    ex("`a", "[:`a]")
    ex("`a``b`", "[code·marker:`][code:a``b][code·marker:`]")
    ex("``a`", "[:``a`]")
    ex("`*not em*`", "[code·marker:`][code:*not em*][code·marker:`]")
    ex("`a\nb`", "[code·marker:`][code:a⏎b][code·marker:`]", "code spans may span lines of one paragraph")
    ex("`a\n\nb`", "[:`a⏎⏎b`]")
    ex("\\`a`", "[esc:\\`][:a`]")
    ex("`a\\`", "[code·marker:`][code:a\\][code·marker:`]", "backslashes are literal inside code spans")
    ex("*a `b*` c*", "[italic·marker:*][italic:a ][italic·code·marker:`][italic·code:b*][italic·code·marker:`][italic: c][italic·marker:*]", "code spans bind tighter than emphasis")
    ex("`a` `b`", "[code·marker:`][code:a][code·marker:`][: ][code·marker:`][code:b][code·marker:`]")
    ex("```not fence```", "[code·marker:```][code:not fence][code·marker:```]")
    ex("a `b` c ` d", "[:a ][code·marker:`][code:b][code·marker:`][: c ` d]")
}

private func linkTests() {
    ex("[a](b)", "[marker·link:[][link:a][marker·link:]][marker·dest:(][dest:b][marker·dest:)]")
    ex("[a](b 'c')", "[marker·link:[][link:a][marker·link:]][marker·dest:(][dest:b][: ][dest:'c'][marker·dest:)]")
    ex("[a]( b )", "[marker·link:[][link:a][marker·link:]][marker·dest:(][: ][dest:b][: ][marker·dest:)]")
    ex("[a](<b c>)", "[marker·link:[][link:a][marker·link:]][marker·dest:(][dest:<b c>][marker·dest:)]")
    ex("[a](b", "[:[a](b]")
    ex("[a]", "[:[a]]", "shortcut references are not styled (definitions are not resolved)")
    ex("[a][b]", "[marker·link:[][link:a][marker·link:]][marker·ref:[][ref:b][marker·ref:]]")
    ex("[a][]", "[marker·link:[][link:a][marker·link:]][marker·ref:[]]")
    ex("arr[i][j]", "[:arr[i][j]]", "reference links directly after a word are not styled (deliberate)")
    ex("![a](b)", "[marker·image:![][image:a][marker·image:]][marker·dest·image:(][dest·image:b][marker·dest·image:)]")
    ex("![a][r]", "[marker·image:![][image:a][marker·image:]][marker·image·ref:[][image·ref:r][marker·image·ref:]]")
    ex("[*a*](b)", "[marker·link:[][italic·marker·link:*][italic·link:a][italic·marker·link:*][marker·link:]][marker·dest:(][dest:b][marker·dest:)]")
    ex("**[a](b)**", "[bold·marker:**][bold·marker·link:[][bold·link:a][bold·marker·link:]][bold·marker·dest:(][bold·dest:b][bold·marker·dest:)][bold·marker:**]")
    ex("[a [b](c) d](e)", "[:[a ][marker·link:[][link:b][marker·link:]][marker·dest:(][dest:c][marker·dest:)][: d](e)]", "links cannot contain links")
    ex("[a\nb](c)", "[marker·link:[][link:a⏎b][marker·link:]][marker·dest:(][dest:c][marker·dest:)]")
    ex("[a](b)[c](d)", "[marker·link:[][link:a][marker·link:]][marker·dest:(][dest:b][marker·dest:)][marker·link:[][link:c][marker·link:]][marker·dest:(][dest:d][marker·dest:)]")
    ex("<https://x.org>", "[marker·auto:<][auto:https://x.org][marker·auto:>]")
    ex("<a@b.co>", "[marker·auto:<][auto:a@b.co][marker·auto:>]")
    ex("<not a link", "[:<not a link]")
    ex("<not a link>", "[html:<not a link>]", "any well-formed tag is inline HTML")
    ex("http://x.org", "[auto:http://x.org]")
    ex("see https://x.org/a?b=c. ok", "[:see ][auto:https://x.org/a?b=c][:. ok]")
    ex("www.x.org/p_q_r", "[auto:www.x.org/p_q_r]")
    ex("(http://x.org)", "[:(][auto:http://x.org][:)]")
    ex("ahttp://x.org", "[:ahttp://x.org]", "bare URLs need a boundary before the scheme")
    ex("a_http://x.org_b", "[:a_][auto:http://x.org_b]", "underscore is an allowed boundary")
    ex("[http://x.org](http://y.org)", "[marker·link:[][link:http://x.org][marker·link:]][marker·dest:(][dest:http://y.org][marker·dest:)]")
    ex("http://", "[:http://]")
    ex("text[^1] more", "[:text][marker·fn:[^][fn:1][marker·fn:]][: more]")
    ex("[^a b]", "[:[^a b]]")
}

private func miscInlineTests() {
    ex("\\*not em\\*", "[esc:\\*][:not em][esc:\\*]")
    ex("a \\\\ b", "[:a ][esc:\\\\][: b]")
    ex("\\a", "[:\\a]")
    ex("&amp; &#35; &#x1F600; &bogus &;", "[esc:&amp;][: ][esc:&#35;][: ][esc:&#x1F600;][: &bogus &;]")
    ex("a <b>bold</b> c", "[:a ][html:<b>][:bold][html:</b>][: c]")
    ex("a <!-- c --> b", "[:a ][html:<!-- c -->][: b]")
    ex("<a href=\"x y\" b>", "[html:<a href=\"x y\" b>]")
    ex("<a href=\"x", "[:<a href=\"x]")
    ex("1 < 2 > 0", "[:1 < 2 > 0]")
    ex("trailing spaces  \nnext", "[:trailing spaces  ⏎next]")
    ex("😀 *x*", "[:😀 ][italic·marker:*][italic:x][italic·marker:*]")
    ex("a\tb", "[:a⇥b]")
}

func runEdgeCaseExpectations() {
    Harness.group("expectations: edge cases")
    ex("", "")
    ex("\n", "[:⏎]")
    ex("\n\n\n", "[:⏎⏎⏎]")
    ex("a", "[:a]")
    ex("a\n", "[:a⏎]")
    ex("# h\r\nb\r\n", "[h1·marker:# ][h1:h␍⏎][:b␍⏎]")
    ex("a\rb\r", "[:a␍b␍]")
    ex("> a\r\n> b\r\n", "[q1·marker:> ][q1:a␍⏎][q1·marker:> ][q1:b␍⏎]")
    ex("```\r\nx\r\n```\r\n", "[fence:```␍⏎][codeblock:x␍⏎][fence:```␍⏎]")
    ex("- a\r- b\r", "[list:- ][:a␍][list:- ][:b␍]")
    ex("---\r\na: b\r\n---\r\n", "[marker·fm:---␍⏎][fm:a: b␍⏎][marker·fm:---␍⏎]")
    ex("a\u{0}b\n", "[:a\u{0}b⏎]")
    ex("   \n  \n", "[:   ⏎  ⏎]")
    ex("😀😀😀\n# 😀\n", "[:😀😀😀⏎][h1·marker:# ][h1:😀⏎]")
    ex("1. a\n   - b\n     ```\n     c\n     ```\n", "[list:1. ][:a⏎   ][list:- ][:b⏎     ][fence:```⏎][:     ][codeblock:c⏎][:     ][fence:```⏎]")
    // Everything is plain when there is nothing to style.
    ex("just words", "[:just words]")

    Harness.group("expectations: containers and tabs")
    ex("- a\n\t- b\n", "[list:- ][:a⏎⇥][list:- ][:b⏎]")
    ex("  \tcode\n", "[codeblock:  ⇥code⏎]", "a tab advances to the next multiple of 4 columns")
    ex(">\tcode\n", "[q1·marker:>⇥][q1:code⏎]")
    ex("1. a\n\n   ```\n   x\n   ```\n2. b\n", "[list:1. ][:a⏎⏎   ][fence:```⏎][:   ][codeblock:x⏎][:   ][fence:```⏎][list:2. ][:b⏎]")
    ex("- | a |\n  |---|\n  | b |\n", "[list:- ][table·thead·tdelim:|][table·thead: a ][table·thead·tdelim:|][table·thead:⏎][:  ][table·tdelim:|---|⏎][:  ][table·tdelim:|][table: b ][table·tdelim:|][table:⏎]", "tables inside list items")
    ex("> <div>\n> x\n> </div>\n", "[q1·marker:> ][q1·html:<div>⏎][q1·marker:> ][q1·html:x⏎][q1·marker:> ][q1·html:</div>⏎]")
    ex("- a\n- ***\n- b\n", "[list:- ][:a⏎][list:- ][hr:***⏎][list:- ][:b⏎]")
    ex("> # H\n> text\n", "[q1·marker:> ][h1·q1·marker:# ][h1·q1:H⏎][q1·marker:> ][q1:text⏎]")
    ex("* * *\n- a\n", "[hr:* * *⏎][list:- ][:a⏎]")
    ex("# [link](u) `c`\n", "[h1·marker:# ][h1·marker·link:[][h1·link:link][h1·marker·link:]][h1·marker·dest:(][h1·dest:u][h1·marker·dest:)][h1: ][h1·code·marker:`][h1·code:c][h1·code·marker:`][h1:⏎]")
    ex("- [ ] [x](y) **b**\n", "[list:- ][task:[ ]][: ][marker·link:[][link:x][marker·link:]][marker·dest:(][dest:y][marker·dest:)][: ][bold·marker:**][bold:b][bold·marker:**][:⏎]")
    ex("[a]: <b> \"t\"\n[c]: d\n", "[marker·ref:[][ref:a][marker·ref:]:][: ][dest:<b>][: ][dest:\"t\"][:⏎][marker·ref:[][ref:c][marker·ref:]:][: ][dest:d][:⏎]")
    ex("> [r]: u\n", "[q1·marker:> ][q1·marker·ref:[][q1·ref:r][q1·marker·ref:]:][q1: ][q1·dest:u][q1:⏎]")
    ex("[^note]: text with *em*\n    second para\n\nnot part\n", "[marker·fn:[^][fn:note][marker·fn:]:][: text with ][italic·marker:*][italic:em][italic·marker:*][:⏎    second para⏎⏎not part⏎]")
    ex("| a |\n|---|\n| `x|y` |\n", "[table·thead·tdelim:|][table·thead: a ][table·thead·tdelim:|][table·thead:⏎][table·tdelim:|---|⏎|][table: `x][table·tdelim:|][table:y` ][table·tdelim:|][table:⏎]", "pipes split cells even inside code spans (GFM)")
}
