// MARK: - ATX headings (4.2)

private func specHeadings() {
    specGroupStart("atx-heading")
    let S = SpecKind.spec
    sx(S, "# foo\n", "[h1·marker:# ][h1:foo⏎]")
    sx(S, "## foo\n", "[h2·marker:## ][h2:foo⏎]")
    sx(S, "### foo\n", "[h3·marker:### ][h3:foo⏎]")
    sx(S, "#### foo\n", "[h4·marker:#### ][h4:foo⏎]")
    sx(S, "##### foo\n", "[h5·marker:##### ][h5:foo⏎]")
    sx(S, "###### foo\n", "[h6·marker:###### ][h6:foo⏎]")
    spPlain(S, "####### foo")
    spPlain(S, "#5 bolt\n\n#hashtag")
    sx(S, "\\## foo", "[esc:\\#][:# foo]")
    sh(S, "# foo *bar* \\*baz\\*\n", ["+h1 foo ", "+h1,italic bar", "+h1,esc \\*"])
    sh(S, "#                  foo                     \n", ["+h1 foo", "+h1,marker #"])
    sh(S, " ### foo\n  ## foo\n   # foo\n", ["+h3 foo", "+h2 foo@@2", "+h1 foo@@3"])
    sx(S, "    # foo", "[codeblock:    # foo]")
    spPlain(S, "foo\n    # bar")
    sh(S, "## foo ##\n  ###   bar    ###\n", ["+h2 foo", "+h2,marker ##@@2", "+h3 bar", "+h3,marker ###"])
    sh(S, "# foo ##################################\n##### foo ##\n", ["+h1 foo", "+h5 foo@@2", "+marker,h1 ##################################"])
    sh(S, "### foo ###     \n", ["+h3 foo", "+h3,marker ###@@2"])
    sh(S, "### foo ### b\n", ["+h3 foo ### b", "-marker ### b"])
    sh(S, "# foo#\n", ["+h1 foo#", "-marker foo#"])
    sx(S, "### foo \\###\n## foo #\\##\n# foo \\#\n", "[h3·marker:### ][h3:foo ][esc·h3:\\#][h3:##⏎][h2·marker:## ][h2:foo #][esc·h2:\\#][h2:#⏎][h1·marker:# ][h1:foo ][esc·h1:\\#][h1:⏎]")
    sx(S, "****\n## foo\n****", "[hr:****⏎][h2·marker:## ][h2:foo⏎][hr:****]")
    sx(S, "Foo bar\n# baz\nBar foo", "[:Foo bar⏎][h1·marker:# ][h1:baz⏎][:Bar foo]")
    sx(S, "## \n#\n### ###\n", "[h2·marker:## ][h2:⏎][h1·marker:#][h1:⏎][h3·marker:### ###][h3:⏎]")
    sx(S, "# H1\n## H2\n### H3\n", "[h1·marker:# ][h1:H1⏎][h2·marker:## ][h2:H2⏎][h3·marker:### ][h3:H3⏎]")
    sh(SpecKind.judge, "# Title with `code`, **bold**, [link](u) and a_b_c\n", ["+h1 Title", "+h1,code code", "+h1,bold bold", "+h1,link link", "-italic a_b_c"])
    sh(SpecKind.judge, "# C# and F#\n## Q&A: what?\n", ["+h1 C# and F#", "-marker C# and F#", "+h2 Q&A: what?"])
    sh(SpecKind.judge, "#\tTabbed\n", ["+h1 Tabbed"])
    sh(SpecKind.judge, "# 日本語の見出し 😀\n", ["+h1 日本語の見出し 😀"])

    specGroupStart("setext-heading")
    sh(S, "Foo *bar*\n=========\n\nFoo *bar*\n---------\n", ["+h1 Foo ", "+h1,italic bar", "+h1,marker =========", "+h2 Foo @@2", "+h2,italic bar@@2", "+h2,marker ---------"])
    sh(S, "Foo *bar\nbaz*\n====\n", ["+h1 Foo ", "+h1,italic bar\nbaz", "+h1,marker ===="])
    sh(S, "Foo\n-------------------------\n", ["+h2 Foo", "+h2,marker -------------------------"])
    sh(S, "Foo\n=\n", ["+h1 Foo", "+h1,marker ="], accept: ["plain Foo\n="], "one-character underline")
    sh(S, "Foo\n-\n", ["+h2 Foo"], accept: ["plain Foo\n-"], "one-character underline")
    sh(S, "   Foo\n---\n\n  Foo\n-----\n\n  Foo\n  ===\n", ["+h2 Foo", "+h2 Foo@@2", "+h1 Foo@@3", "+h1,marker ==="])
    sh(S, "    Foo\n    ---\n", ["+codeblock Foo", "+codeblock ---", "-h2 Foo"])
    sh(S, "    Foo\n---\n", ["+codeblock Foo", "+hr ---"])
    sh(S, "Foo\n   ----      \n", ["+h2 Foo"])
    spPlain(S, "Foo\n    ---")
    sx(S, "Foo\n= =\n\nFoo\n--- -", "[:Foo⏎= =⏎⏎Foo⏎][hr:--- -]")
    sh(S, "Foo  \n-----\n", ["+h2 Foo"])
    sh(S, "Foo\\\n----\n", ["+h2 Foo\\"])
    sx(S, "> Foo\n---", "[q1·marker:> ][q1:Foo⏎][hr:---]")
    sx(S, "> foo\nbar\n===", "[q1·marker:> ][q1:foo⏎bar⏎===]")
    sx(S, "- Foo\n---", "[list:- ][:Foo⏎][hr:---]")
    sh(S, "Foo\nBar\n---\n", ["+h2 Foo\nBar", "+h2,marker ---"])
    sx(S, "\n====", "[:⏎====]")
    sx(S, "- foo\n-----", "[list:- ][:foo⏎][hr:-----]")
    sh(S, "    foo\n---", ["+codeblock foo", "+hr ---"])
    sx(S, "> foo\n-----", "[q1·marker:> ][q1:foo⏎][hr:-----]")
    sh(S, "\\> foo\n------", ["+h2 foo", "+esc \\>"])
    sx(S, "Foo\n\nbar\n---\nbaz", "[:Foo⏎⏎][h2:bar⏎][h2·marker:---][h2:⏎][:baz]")
    sx(S, "Foo\nbar\n\n---\n\nbaz", "[:Foo⏎bar⏎⏎][hr:---⏎][:⏎baz]")
    sx(S, "Foo\nbar\n* * *\nbaz", "[:Foo⏎bar⏎][hr:* * *⏎][:baz]")
    sh(S, "Foo\nbar\n\\---\nbaz", ["plain Foo\nbar\n", "+esc \\-", "plain baz"])
}

// MARK: - Thematic breaks (4.1)

private func specRules() {
    specGroupStart("thematic-break")
    let S = SpecKind.spec
    sx(S, "***\n---\n___", "[hr:***⏎][hr:---⏎][hr:___]")
    spPlain(S, "+++")
    spPlain(S, "===")
    spPlain(S, "--\n**\n__")
    sh(S, " ***\n  ***\n   ***", ["+hr ***", "+hr ***@@2", "+hr ***@@3"])
    sx(S, "    ***", "[codeblock:    ***]")
    spPlain(S, "Foo\n    ***")
    sx(S, "_____________________________________", "[hr:_____________________________________]")
    sh(S, " - - -", ["+hr - - -"])
    sh(S, " **  * ** * ** * **", ["+hr **  * ** * ** * **"])
    sh(S, "-     -      -      -", ["+hr -     -      -      -"])
    sh(S, "- - - -    ", ["+hr - - - -"])
    spPlain(S, "_ _ _ _ a\n\na------\n\n---a---")
    sx(S, " *-*", "[: ][italic·marker:*][italic:-][italic·marker:*]")
    sx(S, "- foo\n***\n- bar", "[list:- ][:foo⏎][hr:***⏎][list:- ][:bar]")
    sx(S, "Foo\n***\nbar", "[:Foo⏎][hr:***⏎][:bar]")
    sh(S, "Foo\n---\nbar", ["+h2 Foo", "plain bar"])
    sx(S, "* Foo\n* * *\n* Bar", "[list:* ][:Foo⏎][hr:* * *⏎][list:* ][:Bar]")
    sx(S, "- Foo\n- * * *", "[list:- ][:Foo⏎][list:- ][hr:* * *]")
    sh(S, "***\n", ["+hr ***"])
    sh(S, "* * *\n- - -\n_ _ _\n", ["+hr * * *", "+hr - - -", "+hr _ _ _"])
    sh(SpecKind.judge, "text\n\n* * *\n\nmore", ["+hr * * *", "plain more"])
}

// MARK: - Indented code (4.4)

private func specIndentedCode() {
    specGroupStart("indented-code")
    let S = SpecKind.spec
    sx(S, "    a simple\n      indented code block", "[codeblock:    a simple⏎      indented code block]")
    sh(S, "  - foo\n\n    bar", ["+list - ", "plain foo", "-codeblock bar"])
    sh(S, "1.  foo\n\n    - bar", ["+list 1.  ", "+list - ", "-codeblock bar"])
    sh(S, "    <a/>\n    *hi*\n\n    - one", ["+codeblock <a/>", "+codeblock *hi*", "+codeblock - one", "-italic hi", "-list - one"])
    sx(S, "    a\n\n    b\n", "[codeblock:    a⏎⏎    b⏎]", accept: "[codeblock:    a⏎][:⏎][codeblock:    b⏎]", "blank line between indented code lines")
    sx(S, "    chunk1\n\n    chunk2\n  \n \n \n    chunk3", "[codeblock:    chunk1⏎⏎    chunk2⏎  ⏎ ⏎ ⏎    chunk3]",
       accept: "[codeblock:    chunk1⏎][:⏎][codeblock:    chunk2⏎][:  ⏎ ⏎ ⏎][codeblock:    chunk3]", "several blank lines inside indented code")
    sx(S, "Foo\n    bar", "[:Foo⏎    bar]")
    sx(S, "    foo\nbar", "[codeblock:    foo⏎][:bar]")
    sh(S, "# Heading\n    foo\nHeading\n------\n    foo\n----\n", ["+h1 Heading", "+codeblock foo", "+h2 Heading@@2", "+codeblock foo@@2", "+hr ----@@2"])
    sx(S, "        foo\n    bar", "[codeblock:        foo⏎    bar]")
    sh(S, "\n    \n    foo\n    ", ["+codeblock foo"])
    sx(S, "\tfoo\tbaz\t\tbim", "[codeblock:⇥foo⇥baz⇥⇥bim]")
    sx(S, "  \tfoo\tbaz\t\tbim", "[codeblock:  ⇥foo⇥baz⇥⇥bim]")
    sx(S, "    a\n\ta", "[codeblock:    a⏎⇥a]")
    sh(S, "- foo\n\n\tbar", ["+list - ", "-codeblock bar"])
    sx(S, "    foo\n\tbar", "[codeblock:    foo⏎⇥bar]")
    sh(S, "#\tFoo", ["+h1 Foo"])
    sh(S, "*\t*\t*\t", ["+hr *"])
    sh(S, "1.  A paragraph\n    with two lines.\n\n        indented code\n\n    > A block quote.\n", ["+list 1.  ", "+codeblock indented code", "+q1 A block quote."],
       accept: ["+list 1.  ", "-codeblock indented code", "+q1 A block quote."], "indented code inside a list item")
    sh(SpecKind.judge, "Intro:\n\n    $ make install\n    $ make test\n\nafter *em*", ["+codeblock $ make install", "+codeblock $ make test", "+italic em", "plain after "])
    sh(SpecKind.judge, "> quote\n\n    code after quote\n", ["+codeblock code after quote"])
}

// MARK: - Fenced code (4.5)

private func specFencedCode() {
    specGroupStart("fenced-code")
    let S = SpecKind.spec
    sx(S, "```\n<\n >\n```", "[fence:```⏎][codeblock:<⏎ >⏎][fence:```]")
    sx(S, "~~~\n<\n >\n~~~", "[fence:~~~⏎][codeblock:<⏎ >⏎][fence:~~~]")
    sx(S, "``\nfoo\n``", "[code·marker:``][code:⏎foo⏎][code·marker:``]")
    sx(S, "```\naaa\n~~~\n```", "[fence:```⏎][codeblock:aaa⏎~~~⏎][fence:```]")
    sx(S, "~~~\naaa\n```\n~~~", "[fence:~~~⏎][codeblock:aaa⏎```⏎][fence:~~~]")
    sx(S, "````\naaa\n```\n``````", "[fence:````⏎][codeblock:aaa⏎```⏎][fence:``````]")
    sx(S, "~~~~\naaa\n~~~\n~~~~", "[fence:~~~~⏎][codeblock:aaa⏎~~~⏎][fence:~~~~]")
    sx(S, "```", "[fence:```]")
    sx(S, "`````\n\n```\naaa", "[fence:`````⏎][codeblock:⏎```⏎aaa]")
    sx(S, "> ```\n> aaa\n\nbbb", "[q1·marker:> ][q1·fence:```⏎][q1·marker:> ][q1·codeblock:aaa⏎][:⏎bbb]")
    sx(S, "```\n\n  \n```", "[fence:```⏎][codeblock:⏎  ⏎][fence:```]")
    sx(S, "```\n```", "[fence:```⏎```]")
    sx(S, " ```\n aaa\naaa\n```", "[fence: ```⏎][codeblock: aaa⏎aaa⏎][fence:```]")
    sx(S, "  ```\naaa\n  aaa\naaa\n  ```", "[fence:  ```⏎][codeblock:aaa⏎  aaa⏎aaa⏎][fence:  ```]")
    sx(S, "   ```\n   aaa\n    aaa\n  aaa\n   ```", "[fence:   ```⏎][codeblock:   aaa⏎    aaa⏎  aaa⏎][fence:   ```]")
    sx(S, "    ```\n    aaa\n    ```", "[codeblock:    ```⏎    aaa⏎    ```]")
    sx(S, "```\naaa\n  ```", "[fence:```⏎][codeblock:aaa⏎][fence:  ```]")
    sx(S, "   ```\naaa\n  ```", "[fence:   ```⏎][codeblock:aaa⏎][fence:  ```]")
    sx(S, "```\naaa\n    ```", "[fence:```⏎][codeblock:aaa⏎    ```]")
    sx(S, "~~~~~~\naaa\n~~~ ~~", "[fence:~~~~~~⏎][codeblock:aaa⏎~~~ ~~]")
    sx(S, "foo\n```\nbar\n```\nbaz", "[:foo⏎][fence:```⏎][codeblock:bar⏎][fence:```⏎][:baz]")
    sh(S, "foo\n---\n~~~\nbar\n~~~\n# baz", ["+h2 foo", "+fence ~~~", "+codeblock bar", "+h1 baz"])
    sx(S, "```ruby\ndef foo(x)\n  return 3\nend\n```", "[fence:```][fence·lang:ruby][fence:⏎][codeblock:def foo(x)⏎  return 3⏎end⏎][fence:```]")
    sx(S, "~~~~    ruby startline=3 $%@#$\ndef foo(x)\n  return 3\nend\n~~~~~~~", "[fence:~~~~    ][fence·lang:ruby][fence: startline=3 $%@#$⏎][codeblock:def foo(x)⏎  return 3⏎end⏎][fence:~~~~~~~]")
    sx(S, "````;\n````", "[fence:````][fence·lang:;][fence:⏎````]")
    sx(S, "``` aa ```\nfoo", "[code·marker:```][code: aa ][code·marker:```][:⏎foo]")
    sx(S, "~~~ aa ``` ~~~\nfoo\n~~~", "[fence:~~~ ][fence·lang:aa][fence: ``` ~~~⏎][codeblock:foo⏎][fence:~~~]")
    sx(S, "```\n``` aaa\n```", "[fence:```⏎][codeblock:``` aaa⏎][fence:```]")
    sh(S, "```{r}\nx <- 1\n```\n", ["+fence,lang {r}", "+codeblock x <- 1"])
    sh(S, "```c++\nint x;\n```\n", ["+fence,lang c++"])
    sh(S, "```js title=\"a.js\" {1,3}\nx\n```\n", ["+fence,lang js", "+fence  title=\"a.js\" {1,3}", "-lang title"])
    sh(S, "``` \nx\n```\n", ["+codeblock x", "+fence ``` "])
    sh(S, "```\r\ncode *x*\r\n```\r\ntext\r\n", ["+codeblock code *x*", "plain text"])
    sh(S, "```\n**not bold** _not em_ <b>x</b> [a](b) # h\n```\n", ["+codeblock **not bold** _not em_ <b>x</b> [a](b) # h", "-bold not bold", "-html <b>"])
    sh(S, "```\nunclosed *x*\n\n# still code\n", ["+codeblock unclosed *x*", "+codeblock # still code", "-h1 still code"])
    // Fences in containers: realistic documentation layouts
    sh(S, "1. Step one:\n```bash\ncmd\n```\n2. Step two\n", ["+list 1. ", "+fence ```", "+codeblock cmd", "+list 2. ", "-codeblock Step two"])
    sh(S, "- item\n    ```\n    code\n    ```\n- next\n", ["+list - ", "+fence ```", "+codeblock code", "+list - @@2", "-codeblock next"])
    sh(S, "- item\n  ```\n  code\n```\n- next\n", ["+codeblock code", "+codeblock - next", "-list - next"])
    sh(S, "> ```js\n> x\n> ```\n", ["+q1,fence,lang js", "+q1,codeblock x"])
    sh(S, "1. a\n\n   ```sh\n   cmd\n   ```\n\n2. b\n", ["+list 1. ", "+fence,lang sh", "+codeblock cmd", "+list 2. ", "plain b"])
    sh(S, "* a\n\n  ```\n  x\n  ```\n* b\n", ["+codeblock x", "+list * @@2", "plain b"])
    sh(S, "- a\n  - b\n    ```\n    x\n    ```\n  - c\n", ["+codeblock x", "+list - @@3", "plain c"])
    sh(S, "text\n```\ncode\n```\n```\nmore\n```\ntail\n", ["+codeblock code", "+codeblock more", "plain tail"])
    sh(SpecKind.judge, "```\ncode\n```\nnot code *em*\n", ["plain not code ", "+italic em"])
    sh(SpecKind.judge, "~~~md\n```\ninner\n```\n~~~\nafter\n", ["+codeblock ```@@1", "+codeblock inner", "+fence ~~~@@2", "plain after"])
    sh(SpecKind.judge, "``` js \nx\n```\n", ["+fence,lang js", "+codeblock x"])
}

// MARK: - Block quotes (5.1)

private func specQuotes() {
    specGroupStart("block-quote")
    let S = SpecKind.spec
    sx(S, "> # Foo\n> bar\n> baz", "[q1·marker:> ][h1·q1·marker:# ][h1·q1:Foo⏎][q1·marker:> ][q1:bar⏎][q1·marker:> ][q1:baz]")
    sh(S, "># Foo\n>bar\n> baz", ["+h1,q1 Foo", "+q1 bar", "+q1 baz", "+marker,q1 >"])
    sh(S, "   > # Foo\n   > bar\n > baz", ["+h1,q1 Foo", "+q1 bar", "+q1 baz"])
    sx(S, "    > # Foo\n    > bar\n    > baz", "[codeblock:    > # Foo⏎    > bar⏎    > baz]")
    sh(S, "> # Foo\n> bar\nbaz", ["+q1 bar", "+q1 baz"])
    sh(S, "> bar\nbaz\n> foo", ["+q1 bar", "+q1 baz", "+q1 foo"])
    sx(S, "> foo\n---", "[q1·marker:> ][q1:foo⏎][hr:---]")
    sx(S, "> - foo\n- bar", "[q1·marker:> ][q1·list:- ][q1:foo⏎][list:- ][:bar]")
    sh(S, ">     foo\n    bar", ["+q1,codeblock foo", "+codeblock bar", "-q1 bar"])
    sh(S, "> ```\nfoo\n```", ["+q1,fence ```", "plain foo", "+fence ```@@2"])
    sh(S, "> foo\n    - bar", ["+q1 foo", "+q1 bar", "-list - "])
    sx(S, ">", "[q1·marker:>]")
    sx(S, "> foo\n\n> bar", "[q1·marker:> ][q1:foo⏎][:⏎][q1·marker:> ][q1:bar]")
    sx(S, "> foo\n> bar", "[q1·marker:> ][q1:foo⏎][q1·marker:> ][q1:bar]")
    sx(S, "> foo\n>\n> bar", "[q1·marker:> ][q1:foo⏎][q1·marker:>][q1:⏎][q1·marker:> ][q1:bar]")
    sx(S, "foo\n> bar", "[:foo⏎][q1·marker:> ][q1:bar]")
    sx(S, "> aaa\n***\n> bbb", "[q1·marker:> ][q1:aaa⏎][hr:***⏎][q1·marker:> ][q1:bbb]")
    sx(S, "> bar\n\nbaz", "[q1·marker:> ][q1:bar⏎][:⏎baz]")
    sx(S, "> bar\n>\nbaz", "[q1·marker:> ][q1:bar⏎][q1·marker:>][q1:⏎][:baz]")
    sh(S, "> > > foo\nbar", ["+q3 foo", "+q3 bar"])
    sh(S, ">>> foo\n> bar\n>>baz", ["+q3 foo", "+q3 bar", "+q3 baz"])
    sh(S, "> > a\n> b\n", ["+q2 a", "+q2 b"])
    sh(S, "> 1. > Blockquote\ncontinued here.", ["+q1 1. ", "+q2 Blockquote", "+q2 continued here."], accept: ["+q1 1. ", "+q2 Blockquote", "+q1 continued here."])
    sh(S, "> **Note**\n> Text with `code` and [link](u).\n", ["+q1,bold Note", "+q1,code code", "+q1,link link"])
    sh(S, "> a\n> \n> b\n", ["+q1 a", "+q1 b"])
    sh(SpecKind.judge, "> [!NOTE]\n> Useful information.\n", ["+q1 [!NOTE]", "+q1 Useful information.", "-link [!NOTE]"])
    sh(SpecKind.judge, "> - item one\n> - item two\n>\n> para\n", ["+q1,list - ", "+q1 item one", "+q1 para"])
    sh(SpecKind.judge, "> quote\n> > nested\n> back\n", ["+q1 quote", "+q2 nested"])
    sh(SpecKind.judge, "> | a | b |\n> |---|---|\n> | 1 | 2 |\n", ["+q1,table a", "+q1,tdelim ---"])
    sh(SpecKind.judge, ">text without space\n", ["+q1 text without space", "+q1,marker >"])
}

// MARK: - Lists, task lists (5.2-5.4, GFM)

private func specLists() {
    specGroupStart("list")
    let S = SpecKind.spec
    sx(S, "A paragraph\nwith two lines.\n\n    indented code\n\n> A block quote.", "[:A paragraph⏎with two lines.⏎⏎][codeblock:    indented code⏎][:⏎][q1·marker:> ][q1:A block quote.]")
    sh(S, "- one\n\n two", ["+list - ", "plain one", "plain two"])
    sh(S, "- one\n\n  two", ["+list - ", "plain two"])
    spPlain(S, "-one\n\n2.two")
    sh(S, "123456789. ok", ["+list 123456789. "])
    spPlain(S, "1234567890. not ok")
    sh(S, "0. ok\n003. ok", ["+list 0. ", "+list 003. "])
    spPlain(S, "-1. not ok")
    sx(S, "10) foo\n    - bar", "[list:10) ][:foo⏎    ][list:- ][:bar]")
    sx(S, "- - foo", "[list:- - ][:foo]")
    sx(S, "1. - 2. foo", "[list:1. - 2. ][:foo]")
    sh(S, "- # Foo\n- Bar\n  ---\n  baz", ["+h1 Foo", "+list - @@2", "+h2 Bar", "plain baz"])
    sh(S, "- foo\n- bar\n+ baz", ["+list - ", "+list - @@2", "+list + "])
    sh(S, "1. foo\n2. bar\n3) baz", ["+list 1. ", "+list 2. ", "+list 3) "])
    sx(S, "Foo\n- bar\n- baz", "[:Foo⏎][list:- ][:bar⏎][list:- ][:baz]")
    spPlain(S, "The number of windows in my house is\n14.  The number of doors is 6.")
    sh(S, "The number of windows in my house is\n1.  The number of doors is 6.", ["plain The number", "+list 1.  "])
    sh(S, "- foo\n\n- bar\n\n\n- baz", ["+list - ", "+list - @@2", "+list - @@3"])
    sx(S, "* a\n*\n\n* c", "[list:* ][:a⏎][list:*][:⏎⏎][list:* ][:c]")
